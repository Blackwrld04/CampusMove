const OAU_BOUNDS = {
  south: 7.492259,
  west: 4.493065,
  north: 7.562359,
  east: 4.575073
};

/**
 * Ray-casting point-in-polygon test with a fast bounding-box rejection first.
 */
function isInsideOAU(lat, lng) {
  if (
    !Number.isFinite(lat) ||
    !Number.isFinite(lng) ||
    lat < OAU_BOUNDS.south ||
    lat > OAU_BOUNDS.north ||
    lng < OAU_BOUNDS.west ||
    lng > OAU_BOUNDS.east
  ) {
    return false;
  }

  let inside = false;

  for (
    let i = 0, j = OAU_BOUNDARY.length - 1;
    i < OAU_BOUNDARY.length;
    j = i++
  ) {
    const [latI, lngI] = OAU_BOUNDARY[i];
    const [latJ, lngJ] = OAU_BOUNDARY[j];

    if (
      (latI > lat) !== (latJ > lat) &&
      lng < ((lngJ - lngI) * (lat - latI)) / (latJ - latI) + lngI
    ) {
      inside = !inside;
    }
  }

  return inside;
}

